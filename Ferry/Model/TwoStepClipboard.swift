import AppKit

/// "Paste twice" mode. Step 1 offers only the image files, lazily: the moment an app actually reads
/// them (a paste), Ferry learns of it and, once the reads settle, replaces the clipboard with the
/// text (images shown as `[Image N]`) for the second paste.
/// Both steps also carry the Ferry fragment, so pasting into Ferry always restores text and images.
final class TwoStepClipboard {
    static let shared = TwoStepClipboard()

    /// Quiet time after the last read before switching to the text (one paste reads several items).
    var swapDelay: TimeInterval = 0.3

    /// nspasteboard.org markers. Clipboard watchers (Raycast's history, QQ, Maccy…) skip such content
    /// instead of reading it; a read would look like a paste and switch to the text too early, and QQ
    /// would even rewrite the clipboard. Verified: with all three, nothing on a Mac running Raycast and
    /// QQ read the step-1 content.
    static let skipMarkers: [NSPasteboard.PasteboardType] = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
    ].map { NSPasteboard.PasteboardType(rawValue: $0) }

    private struct Pending {
        let pasteboard: NSPasteboard
        let changeCount: Int
        let text: String
        let fragment: Data?
    }

    /// Supplies one image's file URL when an app reads it, and reports the read.
    private final class FileURLProvider: NSObject, NSPasteboardItemDataProvider {
        let url: URL
        let onRead: () -> Void
        init(url: URL, onRead: @escaping () -> Void) { self.url = url; self.onRead = onRead }

        func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
            item.setString(url.absoluteString, forType: .fileURL)
            onRead()
        }
    }

    private var pending: Pending?
    private var providers: [FileURLProvider] = [] // the pasteboard doesn't retain them
    private var swapWork: DispatchWorkItem?

    /// Writes step 1. Returns the number of images offered; 0 means nothing was written.
    /// `stripMarkdown`: the step-2 text leaves out Markdown syntax; the Ferry fragment keeps it.
    @discardableResult
    func write(_ fragment: Fragment, to pasteboard: NSPasteboard, stripMarkdown: Bool = false) -> Int {
        reset()
        let textFragment = stripMarkdown ? fragment.strippingMarkdown() : fragment
        let imageURLs = FerryPasteboard.attachableImageURLs(fragment)
        guard !imageURLs.isEmpty else { return 0 }
        let fragmentData = try? JSONEncoder().encode(fragment)

        let items = imageURLs.enumerated().map { index, url -> NSPasteboardItem in
            let provider = FileURLProvider(url: url) { [weak self] in self?.scheduleSwap() }
            providers.append(provider)
            let item = NSPasteboardItem()
            item.setDataProvider(provider, forTypes: [.fileURL])
            for marker in Self.skipMarkers { item.setData(Data(), forType: marker) }
            if index == 0, let fragmentData { item.setData(fragmentData, forType: FerryPasteboard.fragmentType) }
            return item
        }
        pasteboard.prepareForNewContents(with: .currentHostOnly) // keep Universal Clipboard from fetching it
        pasteboard.writeObjects(items)

        // Images only: no second step, every paste repeats the images.
        if Self.hasText(textFragment) {
            let text = ClipboardRenderer.textWithImagePlaceholders(textFragment, attached: imageURLs.map(\.path))
            pending = Pending(pasteboard: pasteboard, changeCount: pasteboard.changeCount, text: text, fragment: fragmentData)
        }
        return imageURLs.count
    }

    static func hasText(_ fragment: Fragment) -> Bool {
        fragment.segments.contains { !($0.text ?? "").trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
    }

    // MARK: Step 2

    private func scheduleSwap() {
        guard pending != nil else { return }
        swapWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.swapToText() }
        swapWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + swapDelay, execute: work)
    }

    private func swapToText() {
        guard let pending, pending.pasteboard.changeCount == pending.changeCount else { return reset() }
        reset()
        let item = NSPasteboardItem()
        item.setString(pending.text, forType: .string)
        if let fragment = pending.fragment { item.setData(fragment, forType: FerryPasteboard.fragmentType) }
        pending.pasteboard.clearContents()
        pending.pasteboard.writeObjects([item])
    }

    private func reset() {
        swapWork?.cancel()
        swapWork = nil
        pending = nil
        providers = []
    }
}
